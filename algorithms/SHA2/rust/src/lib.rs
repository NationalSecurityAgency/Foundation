/// This function computes the Secure Hash Algorithm with a digest
/// size of 224 bits (SHA-224) [FIPS-PUB-180-4 Section 6.3].
///
/// # Panics
///
/// This function will not panic.
#[allow(clippy::unreadable_literal)]
#[must_use]
pub fn SHA224(M: &[u8]) -> [u8; 28] {
    // Initial hash value for SHA-224 [FIPS-PUB-180-4 Section 5.3.2].
    let H0_224: [u32; 8] = [
        0xc1059ed8, 0x367cd507, 0x3070dd17, 0xf70e5939, 0xffc00b31, 0x68581511, 0x64f98fa7,
        0xbefa4fa4,
    ];

    let Mpadded = pad32(M);
    let H_final = Mpadded.chunks_exact(64).fold(H0_224, |H, Mnext| {
        inner::<64, u32>(
            &sigma_256_0,
            &sigma_256_1,
            &SIGMA_256_0,
            &SIGMA_256_1,
            &K_256,
            H,
            parse32(&Mnext.try_into().unwrap()),
        )
    });

    let mut hash: Vec<u8> = Vec::new();
    for word in &H_final[0..7] {
        hash.extend_from_slice(&word.to_be_bytes());
    }
    hash.try_into().unwrap()
}

